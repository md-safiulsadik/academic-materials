
public class Calculator {

    public void sum() {
        System.out.println("This is 1st sum: ");
    }

    public void sum(int x, int y) {
        System.out.println("This is 2nd sum: " + x + y);
    }

    public void sum(float x, float y) {
        System.out.println("This is 3rd sum: " + x+y);
    }
}


